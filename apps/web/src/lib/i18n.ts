export type I18nKey = keyof typeof en;

export function detectBrowserLocale(acceptLanguage: string | null | undefined): UiLocale {
  if (!acceptLanguage) return "en";
  const parts = acceptLanguage.split(",").map((p) => p.trim().split(";")[0]?.toLowerCase() || "");
  for (const lang of parts) {
    if (lang === "zh" || lang.startsWith("zh-")) return "zh";
  }
  return "en";
}

/**
 * Resolve UI locale: persisted setting wins; if unset, use Accept-Language (zh* → zh).
 */
export function resolveUiLocale(
  stored: UiLocale | null | undefined,
  acceptLanguage?: string | null
): UiLocale {
  if (stored === "zh" || stored === "en") return stored;
  return detectBrowserLocale(acceptLanguage);
}

export function t(
  locale: UiLocale,
  key: I18nKey,
  vars?: Record<string, string | number>
): string {
  let s = locale === "zh" ? zh[key] || en[key] : en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

